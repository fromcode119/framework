import fs from 'fs';
import path from 'path';

/** What `stack up` was asked for, once the defaults are filled in. */
export interface StackRequest {
  readonly name: string;
  readonly framework: string;
  readonly plugins: readonly string[];
  readonly version: string;
  readonly port: number;
}

/**
 * The files a local stack runs from.
 *
 * A stack is a copy of `deploy/`, an `.env` beside it, and one overlay that points the containers
 * at a worktree. It deliberately does NOT join the shared `proxy` network and does NOT register a
 * Traefik route: two stacks that both claim `*.framework.local` contend for the same hostnames, and
 * one silently wins (seen as 307 → 404 on the shared stack). Instead each stack publishes one port
 * on 127.0.0.1 and gets its own network.
 *
 * Hostnames still work, because macOS resolves every `*.localhost` name to 127.0.0.1 with no
 * configuration at all — verified to arbitrary depth. So `console.<stack>.localhost:<port>` reaches
 * this stack's gateway with the Host header the gateway routes on, and nothing had to be written to
 * `/etc/hosts` or resolved by dnsmasq.
 */
export class StackPlan {
  /** Services whose container path must come from the worktree rather than the image. */
  private static readonly RUNTIME_SERVICES = ['api', 'extension-host', 'site-extension-host'];

  constructor(private readonly request: StackRequest) {}

  /**
   * The stack's own directory. Outside the scratchpad on purpose: a scratchpad is wiped by a Mac
   * restart, and a stack that loses its `.env` cannot be torn down by name afterwards.
   */
  static rootFor(name: string, home: string): string {
    return path.join(home, '.fromcode-stacks', name);
  }

  /**
   * `.env` for the stack.
   *
   * `docker-compose.images.yml` carries `build: !reset null`, so naming a released VERSION here is
   * what makes `stack up` build nothing at all — it reuses an image already on the machine and
   * mounts this worktree's code over it.
   */
  env(): string {
    const { name, version, port } = this.request;
    return [
      `# Generated by \`fromcode stack up ${name}\`. Edit the stack, not this file.`,
      `COMPOSE_PROJECT_NAME=${name}`,
      'COMPOSE_FILE=docker-compose.full-stack.yml:docker-compose.images.yml:docker-compose.stack.yml',
      'COMPOSE_PROFILES=single-domain',
      `VERSION=${version}`,
      `GATEWAY_PORT=127.0.0.1:${port}`,
      // The edge publishes 443 as well, and its default (127.0.0.1:8443) is one fixed port every
      // stack would fight over — the second stack dies with "port is already allocated" after the
      // other ten containers have already started.
      `GATEWAY_TLS_PUBLISH=127.0.0.1:${StackPlan.tlsPortFor(port)}`,
      // Its own network, not the shared `proxy` one — see the class comment.
      `EXTERNAL_PROXY_NETWORK=${name}-edge`,
      'PROXY_NETWORK_EXTERNAL=false',
      // Without this every container dies with "journald is not enabled on this host".
      'PLATFORM_LOG_DRIVER=json-file',
      '',
    ].join('\n');
  }

  /**
   * The overlay that points the containers at the worktree.
   *
   * Only paths that EXIST are mounted. That is not tidiness: mounting a directory that is empty on
   * the host HIDES the image's baked copy, and a missing `dist` or `public/fc-runtime` then makes
   * the storefront serve no runtime and every plugin admin bundle fail to load. Anything this
   * worktree has not built falls through to the image instead.
   */
  overlay(): string {
    const lines: string[] = [
      '# Generated by `fromcode stack up`. Points this stack at a worktree.',
      '#',
      '# Only built paths are mounted: an empty host directory would hide the image\'s own copy and',
      '# break the runtime bundles rather than simply having no effect.',
      'services:',
    ];

    const runtime = this.runtimeMounts();
    for (const service of StackPlan.RUNTIME_SERVICES) {
      lines.push(`  ${service}:`, '    volumes:');
      for (const mount of runtime) lines.push(`      - ${mount}`);
    }

    const admin = this.appMounts('admin');
    if (admin.length) {
      lines.push('  admin:', '    volumes:');
      for (const mount of admin) lines.push(`      - ${mount}`);
    }

    const frontend = this.appMounts('frontend');
    if (frontend.length) {
      lines.push('  frontend:', '    volumes:');
      for (const mount of frontend) lines.push(`      - ${mount}`);
    }

    lines.push('');
    return lines.join('\n');
  }

  /**
   * Built framework packages, plus every named plugin.
   *
   * `dist` rather than `src`: these containers run the released image, which starts compiled
   * output. Mounting sources over it would change nothing, which is the kind of "verified" that is
   * worse than not checking at all.
   */
  private runtimeMounts(): string[] {
    const mounts: string[] = [];

    for (const pkg of this.builtPackages()) {
      mounts.push(`${path.join(this.request.framework, 'packages', pkg, 'dist')}:/app/packages/${pkg}/dist`);
    }
    for (const plugin of this.request.plugins) {
      mounts.push(`${plugin}:/app/plugins/${path.basename(plugin)}`);
    }
    return mounts;
  }

  /** A Next app serves its build, so `.next` and `public` are what a worktree has to supply. */
  private appMounts(app: 'admin' | 'frontend'): string[] {
    const mounts: string[] = [];
    const base = path.join(this.request.framework, 'packages', app);

    for (const directory of ['.next', 'public']) {
      const host = path.join(base, directory);
      if (fs.existsSync(host)) mounts.push(`${host}:/app/packages/${app}/${directory}`);
    }
    for (const plugin of this.request.plugins) {
      mounts.push(`${plugin}:/app/plugins/${path.basename(plugin)}`);
    }
    return mounts;
  }

  /** Every workspace package this worktree has actually built. */
  private builtPackages(): string[] {
    const packages = path.join(this.request.framework, 'packages');
    if (!fs.existsSync(packages)) return [];

    return fs
      .readdirSync(packages)
      .filter((name) => fs.existsSync(path.join(packages, name, 'dist')))
      .sort();
  }

  /**
   * The TLS port that goes with an http port.
   *
   * A fixed offset rather than a second allocation, so one number identifies a stack and the pair
   * can never drift apart. 400 keeps every stack's TLS port above every stack's http port until
   * there are 400 of them at once.
   */
  static tlsPortFor(port: number): number {
    return port + 400;
  }

  /** The three hostnames this stack answers on, for the command to print. */
  urls(site?: string): string[] {
    const { name, port } = this.request;
    const urls = [`http://console.${name}.localhost:${port}`];
    if (site) {
      urls.push(`http://portal.${site}.${name}.localhost:${port}`, `http://${site}.${name}.localhost:${port}`);
    }
    return urls;
  }
}
